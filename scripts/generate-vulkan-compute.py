"""Generate paired host/guest compute feature metadata from one wire schema."""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
p = argparse.ArgumentParser(description=__doc__)
p.add_argument('--check', action='store_true')
a = p.parse_args()
schema = json.loads((root / 'runtime/crates/trames-vulkan/compute-profile.json').read_text())
rs = ['// SPDX-License-Identifier: GPL-3.0-or-later', '// Generated by scripts/generate-vulkan-compute.py; edit compute-profile.json.']
c = rs.copy()
rs += ['pub(super) const EXTENSIONS: &[(u64, &std::ffi::CStr, u32)] = &[']
for e in schema['extensions']:
    minimum = 'vk::API_VERSION_1_1' if e['minimum_api'] == 11 else 'vk::API_VERSION_1_0'
    rs += [f'    (1 << {e["index"]}, c"{e["extension"]}", {minimum}),']
rs += ['];']
for e in schema['extensions']:
    if e['name'] in ('storage_class', 'maintenance3'):
        rs += [f'pub(super) const EXT_{e["name"].upper()}: u64 = 1 << {e["index"]};']
rs += ['compute_features! {']
bit_mask = 0
for f in schema['features']:
    fields = ', '.join(str(f['bit'] + i) + ' => ' + x['rust'] + ' : ' + ('true' if x.get('expose', True) else 'false') for i, x in enumerate(f['fields']))
    rs += [f'    {f["name"]}: {f["type"]}, {f["extension"]}, {f["bit"]} => [{fields}];']
    for i, field in enumerate(f['fields']):
        assert not bit_mask & (1 << (f['bit'] + i))
        bit_mask |= 1 << (f['bit'] + i)
rs += ['}']
for f in schema['features']:
    for i, field in enumerate(f['fields']):
        if field['rust'] in ('buffer_device_address', 'subgroup_size_control', 'compute_full_subgroups', 'shader_shared_float32_atomic_add', 'shader_shared_float32_atomics'):
            rs += [f'pub(super) const {field["rust"].upper()}: u64 = 1 << {f["bit"] + i};']
rs += ['compute_properties! {']
for q in schema['properties']:
    fields = ', '.join(x['rust'] + ('.as_raw() as u32' if x['kind'] == 'ShaderFloatControlsIndependence' else '.as_raw()' if x['kind'] not in ('u32', 'Bool32') else '') for x in q['fields'])
    ext = '0' if q['extension'] is None else '1 << ' + str(q['extension'])
    rs += [f'    {q["type"]}, {ext} => [{fields}];']
rs += ['}']
c += ['static const struct compute_extension compute_extensions[] = {']
for e in schema['extensions']:
    c += [f'    {{"{e["extension"]}", 1UL << {e["index"]}}},']
c += ['};', 'static const struct compute_feature compute_features[] = {']
for f in schema['features']:
    promoted = schema['extensions'][f['extension']]['promoted']
    api = 'VK_API_VERSION_1_1' if promoted == 11 else 'UINT32_MAX'
    c += [f'    {{VK_STRUCTURE_TYPE_{f["structure_type"]}, offsetof(Vk{f["type"]}, {f["fields"][0]["c"]}), {len(f["fields"])}, {f["bit"]}, 1UL << {f["extension"]}, {api}}},']
c += ['};', 'static const struct compute_aggregate compute_aggregates[] = {']
for q in schema['aggregates']:
    mapping = ', '.join(str(f['bit']) for f in q['fields'])
    c += [f'    {{VK_STRUCTURE_TYPE_{q["structure_type"]}, offsetof(Vk{q["type"]}, {q["fields"][0]["c"]}), {len(q["fields"])}, {q["seen_mask"]}UL, {{{mapping}}}}},']
c += ['};', 'static const struct compute_property compute_properties[] = {']
for q in schema['properties']:
    ext = '0' if q['extension'] is None else '1UL << ' + str(q['extension'])
    c += [f'    {{VK_STRUCTURE_TYPE_{q["structure_type"]}, offsetof(Vk{q["type"]}, {q["fields"][0]["c"]}), {len(q["fields"]) * 4}, {ext}}},']
c += ['    {VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_MAINTENANCE_3_PROPERTIES, offsetof(VkPhysicalDeviceMaintenance3Properties, maxPerSetDescriptors), 16, 1UL << 16},', '};']
outputs = {root / 'runtime/crates/trames-vulkan/src/backend/compute_schema.rs': '\n'.join(rs) + '\n', root / 'accelerator/vulkan/compute-schema.inc': '\n'.join(c) + '\n'}
for path, content in outputs.items():
    if a.check:
        assert path.read_text() == content, 'refresh compute metadata: ' + str(path)
    else:
        path.write_text(content)
print('paired compute metadata verified' if a.check else 'paired compute metadata generated')
